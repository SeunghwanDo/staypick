SUPPORTED_LANGS = ["ko", "en", "ja", "es"]


def normalize_lang(lang: str) -> str:
    lang = (lang or "").strip().lower()
    if not lang:
        return "ko"
    # Accept 'en-US' => 'en'
    if "-" in lang:
        lang = lang.split("-", 1)[0]
    if lang in SUPPORTED_LANGS:
        return lang
    return "ko"


def lang_display_name(code: str) -> str:
    code = normalize_lang(code)
    return {
        "ko": "한국어",
        "en": "English",
        "ja": "日本語",
        "es": "Español",
    }.get(code, "한국어")


