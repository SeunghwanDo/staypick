@dataclass
class Translator:
    lang: str = "ko"

    def t(self, key: str, default: Optional[str] = None) -> str:
        lang = normalize_lang(self.lang)
        if key in UI.get(lang, {}):
            return UI[lang][key]
        # fallback to Korean
        if key in UI.get("ko", {}):
            return UI["ko"][key]
        return default or key


def get_translator(lang: str) -> Translator:
    return Translator(lang=normalize_lang(lang))
